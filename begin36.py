#Скорость первого автомобиля V1 км/ч, второго — V2 км/ч, расстояние между
#ними S км. Определить расстояние между ними через T часов, если автомобили
#удаляются друг от друга. Данное расстояние равно сумме начального
#расстояния и общего пути, проделанного автомобилями; общий путь = время · суммарная скорость.
V1 = float(input())
V2 = float(input())
S = float(input())
T = float(input())

s_additional = (V1 + V2) * T
s_final = S + s_additional

print(s_additional)
print(s_final)

