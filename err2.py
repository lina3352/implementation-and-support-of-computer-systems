#Прочитать два целых числа и вывести их частное с одним знаком после точки. 
#При делении на ноль вывести «Делить на ноль нельзя». Нечисловой ввод обрабатывать не требуется.
try:
    number = int(input())
    number2 = int(input())
    print(number // number2)
except ZeroDivisionError:
    print("делить на ноль нельзя")
